def jug_distance(a, b, target):
    from collections import deque
    pending=deque([((0,0),0)]);seen={(0,0)}
    while pending:
        (x,y),distance=pending.popleft()
        if target in (x,y): return distance
        xy=min(x,b-y);yx=min(y,a-x)
        for state in [(a,y),(x,b),(0,y),(x,0),(x-xy,y+xy),(x+yx,y-yx)]:
            if state not in seen: seen.add(state);pending.append((state,distance+1))
    return None

