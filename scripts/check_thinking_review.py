"""Exercise the standalone file:// review, including durable review exports."""
from pathlib import Path
import json
from playwright.sync_api import sync_playwright

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/"artifacts/thinking-review"


def run():
    OUT.mkdir(parents=True,exist_ok=True)
    passed=[];errors=[];requests=[]
    def ok(name,condition=True):
        assert condition,name
        passed.append(name)
    with sync_playwright() as p:
        browser=p.chromium.launch(headless=True)
        context=browser.new_context(viewport={"width":1440,"height":960},accept_downloads=True)
        page=context.new_page()
        page.on("pageerror",lambda error:errors.append(str(error)))
        page.on("request",lambda request:requests.append(request.url))
        page.goto((ROOT/"docs/archive/thinking/review.html").as_uri())
        ok("300 questions embedded and listed",page.locator('.entry').count()==300 and page.evaluate('corpus.questions.length')==300)
        ok("answer initially hidden",page.locator('#solution').is_hidden())
        first=page.locator('article').get_attribute('data-question')
        page.locator('#answer-toggle').click()
        ok("answer revealed",page.locator('#solution').is_visible())
        page.locator('#next').click()
        ok("next question resets reveal",page.locator('article').get_attribute('data-question')!=first and page.locator('#solution').is_hidden())
        page.locator('#always-answer').check()
        page.locator('#next').click()
        ok("persistent reveal option",page.locator('#solution').is_visible())
        page.locator('#always-answer').uncheck()
        page.locator('.chapter').filter(has_text='概率直觉').click()
        ok("category filtering",page.locator('.entry').count()==30)
        before_random=page.locator('article').get_attribute('data-question')
        page.locator('#random').click()
        ok("random stays in the filtered set and changes question",page.locator('article').get_attribute('data-question')!=before_random and page.evaluate("byId.get(current).category")=="概率直觉")
        page.locator('#clear-filters').click()
        page.locator('#difficulty').select_option('3')
        ok("difficulty filtering",page.locator('.entry').count()==16)
        page.locator('#clear-filters').click()
        page.locator('#search').fill('think-bridge-1')
        ok("ID search",page.locator('.entry').count()==1 and page.locator('article').get_attribute('data-question')=='think-bridge-1')
        note='请核对最短性。测试引号 " 与 <script> 作为普通备注'
        page.locator('#review-note').fill(note)
        page.locator('[data-decision=change]').click()
        page.reload()
        ok("notes and decision survive reload",page.locator('#review-note').input_value()==note and page.locator('[data-decision=change]').get_attribute('aria-pressed')=='true')
        with page.expect_download() as event:page.locator('#export-review').click()
        review_path=OUT/'review-export.json';event.value.save_as(review_path)
        exported=json.loads(review_path.read_text(encoding='utf-8'))
        ok("review download preserves content hash and annotation",exported['reviewed']==1 and exported['entries'][0]['note']==note and exported['entries'][0]['id']=='think-bridge-1' and exported['corpusHash']==page.evaluate('corpus.contentHash'))
        with page.expect_download() as event:page.locator('#export-data').click()
        full_path=OUT/'corpus-export.json';event.value.save_as(full_path)
        ok("full corpus download",len(json.loads(full_path.read_text(encoding='utf-8'))['questions'])==300)
        page.once('dialog',lambda dialog:dialog.accept());page.locator('#reset').click()
        ok("reset affects review only",'已审 0' in page.locator('#audit-count').inner_text() and page.evaluate('corpus.questions.length')==300)
        page.locator('#import-file').set_input_files(review_path)
        page.wait_for_function("document.querySelector('[data-decision=change]').getAttribute('aria-pressed')==='true'")
        ok("import restores annotation",page.locator('#review-note').input_value()==note)
        page.locator('#import-file').set_input_files({"name":"wrong.json","mimeType":"application/json","buffer":json.dumps({"kind":"YOURoom-thinking-review","corpusHash":"wrong","entries":[]}).encode()})
        page.wait_for_function("document.getElementById('toast').textContent.startsWith('导入失败')")
        ok("wrong revision import rejected",page.locator('#review-note').input_value()==note)
        page.locator('#clear-filters').click();page.locator('#status-filter').select_option('change')
        ok("review status filter",page.locator('.entry').count()==1)
        page.locator('#status-filter').select_option('drop')
        ok("empty filter state safe",page.locator('.entry').count()==0 and page.locator('#next').is_disabled())
        page.locator('#clear-filters').click()
        page.locator('.family-line button').click()
        ok("related family view",page.locator('.entry').count()==3)
        page.locator('#clear-filters').click()
        page.locator('.question').click();before=page.locator('article').get_attribute('data-question')
        page.keyboard.press('ArrowRight')
        ok("keyboard navigation",page.locator('article').get_attribute('data-question')!=before)
        page.keyboard.press('Space');ok("keyboard reveal",page.locator('#solution').is_visible())
        page.keyboard.press('1');ok("keyboard keep marker",page.locator('[data-decision=keep]').get_attribute('aria-pressed')=='true')
        # Render every record to catch a missing field or an exceptional label.
        rendered=page.evaluate("""()=>{let count=0;for(const q of questions){select(q.id);if(document.querySelector('.question').textContent!==q.body)throw Error(q.id);if(!document.querySelector('.answer').textContent)throw Error('answer '+q.id);count++;}return count;}""")
        ok("all 300 details render",rendered==300)
        page.evaluate("select('think-truth-island-1')")
        page.locator('#answer-toggle').click();page.locator('#reading').evaluate('(e)=>e.scrollTop=0')
        page.wait_for_timeout(220)
        ok("desktop has no horizontal overflow",page.evaluate('document.documentElement.scrollWidth<=innerWidth'))
        page.screenshot(path=str(OUT/'desktop.png'),full_page=True)
        page.set_viewport_size({"width":390,"height":844})
        ok("mobile no horizontal overflow",page.evaluate('document.documentElement.scrollWidth<=innerWidth'))
        ok("mobile import and export accessible",page.locator('#import-review').is_visible() and page.locator('#export-review').is_visible())
        page.locator('#mobile-category').select_option('信息与判断')
        ok("mobile category filter",page.locator('.entry').count()==30)
        page.locator('#list-toggle').click();ok("mobile index opens",page.locator('.index').is_visible())
        page.locator('.entry').nth(1).click();ok("mobile item selection closes index",not page.locator('.index').is_visible())
        page.locator('#answer-toggle').click()
        page.wait_for_timeout(220)
        page.screenshot(path=str(OUT/'mobile.png'),full_page=True)
        page.set_viewport_size({"width":320,"height":700})
        ok("320px no horizontal overflow",page.evaluate('document.documentElement.scrollWidth<=innerWidth'))
        ok("no script errors",not errors)
        ok("review makes no network requests",all(url.startswith('file:') for url in requests))
        context.close();browser.close()
    report={"checks":len(passed),"passed":passed,"errors":errors,"applicationTestsRun":False}
    (OUT/'browser-checks.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    print(json.dumps(report,ensure_ascii=False,indent=2))


if __name__=='__main__':run()
